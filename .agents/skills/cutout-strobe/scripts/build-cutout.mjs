// Window outlines, as clip-path values in px.
const rect = (x0, y0, x1, y1) => `M${r1(x0)} ${r1(y0)}H${r1(x1)}V${r1(y1)}H${r1(x0)}Z`;
const path = d => `path("${d}")`;
function outline(w, v) {
  const cx = (w.cx ?? 0.5) * W, cy = (w.cy ?? w.y ?? 0.5) * H;
  switch (w.shape) {
    case "full": return NONE;
    case "slit": {
      if (v >= 0.999) return NONE;
      const h = v * H;
      return h < 1 ? null : path(rect(0, clamp(cy - h / 2, 0, H), W, clamp(cy + h / 2, 0, H)));
    }
    case "blinds": {
      // Slats close one after another from the top; v is how much of the stack is still open.
      const n = Number(w.count) || 5, fill = Number(w.fill) || 0.62, pitch = H / n;
      const d = [];
      for (let k = 0; k < n; k++) {
        const open = clamp(v * n - (n - 1 - k), 0, 1);
        const h = pitch * fill * open;
        if (h >= 1) { const mid = pitch * (k + 0.5); d.push(rect(0, mid - h / 2, W, mid + h / 2)); }
      }
      return d.length ? path(d.join("")) : null;
    }
    case "circle": {
      const r = v * H;
      return r < 1 ? null : `circle(${r1(r)}px at ${r1(cx)}px ${r1(cy)}px)`;
    }
    case "cross": {
      // Two bands through one point, at +v and -v degrees: an X that shuts like scissors to a bar.
      const half = ((Number(w.width) || 0.22) * H) / 2, L = W + H;
      const band = deg => {
        const a = (deg * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a);
        const p = [[-L, -half], [L, -half], [L, half], [-L, half]].map(([x, y]) => `${r1(cx + x * c - y * s)} ${r1(cy + x * s + y * c)}`);
        return `M${p[0]}L${p[1]}L${p[2]}L${p[3]}Z`;
      };
      return path(band(v) + band(-v));
    }
    case "quad": {
      // A panel in one corner that grows to the whole frame.
      if (v >= 0.999) return NONE;
      const pw = W * (0.5 + 0.5 * v), ph = H * (0.3 + 0.7 * v), c = w.corner || "tr";
      const x0 = c.includes("r") ? W - pw : 0, y0 = c.includes("b") ? H - ph : 0;
      return path(rect(x0, y0, x0 + pw, y0 + ph));
    }
    default: return null;
  }
}
// The window's value on each of its frames: keys [[frame, value], ...], or from and to with an ease.
const DEFAULTS = { slit: [1, 0.05, "expo"], blinds: [1, 0, "linear"], circle: [0.06, 1.05, "linear"], cross: [50, 0, "linear"], quad: [0, 1, "in"], full: [1, 1, "linear"] };
function windowValues(w, frames) {
  if (w.shape === "none") return null;
  const d = DEFAULTS[w.shape];
  let keys = w.keys;
  if (!keys) {
    const from = Number(w.from ?? d[0]), to = Number(w.to ?? d[1]), over = Math.max(1, Math.min(frames - 1, Number(w.over) || frames - 1)), ease = EASES[w.ease || d[2]];
    return Array.from({ length: frames }, (_, f) => from + (to - from) * ease(Math.min(1, f / over)));
  }
  keys = keys.map(k => [Number(k[0]), Number(k[1])]).sort((a, b) => a[0] - b[0]);
  return Array.from({ length: frames }, (_, f) => {
    if (f <= keys[0][0]) return keys[0][1];
    for (let k = 1; k < keys.length; k++) if (f <= keys[k][0]) { const t = (f - keys[k - 1][0]) / (keys[k][0] - keys[k - 1][0]); return keys[k - 1][1] + (keys[k][1] - keys[k - 1][1]) * t; }
    return keys[keys.length - 1][1];
  });
}

