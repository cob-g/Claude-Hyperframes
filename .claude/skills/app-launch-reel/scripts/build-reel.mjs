function overlays(s) {
  const x = s.exit;
  if (!x) return "";
  if (x.type === "pixel") {
    const n = 8, cw = W / n;
    return `<div class="alr-pixel">${Array.from({ length: n }, (_, i) => `<i class="fill-${x.fill}" style="background-position:${-r3(i * cw)}px 0"></i>`).join("")}</div>`;
  }
  if (x.type === "iris") {
    const nb = TONE_BASE[scenes[s.i + 1].tone];
    return `<div class="alr-iris" style="background:${nb};opacity:.22"></div><div class="alr-iris" style="background:${nb};opacity:.45"></div>`;
  }
  return "";
}

