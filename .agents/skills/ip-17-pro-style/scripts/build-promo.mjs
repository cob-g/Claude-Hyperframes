function localPath(p, where, kind) {
  if (typeof p !== "string" || !p) { fail(`${where} must be a file path.`); return null; }
  if (/^[a-z][a-z0-9+.-]*:/i.test(p) || p.startsWith("//")) { fail(`${where} is a URL (${p}); put the file in the project and use a relative path.`); return null; }
  if (isAbsolute(p)) { fail(`${where} is absolute (${p}); use a path relative to the project.`); return null; }
  const file = resolve(project, p);
  if (file !== project && !file.startsWith(project + sep)) { fail(`${where} points outside the project (${p}).`); return null; }
  if (!existsSync(file) || !statSync(file).isFile()) { fail(`${where}: no file at ${p}`); return null; }
  if (kind && !KINDS[kind].includes(extname(file).toLowerCase())) { fail(`${where}: ${p} is not a ${KINDS[kind].join("/")} file.`); return null; }
  return file;
}
// Decode CSS escapes (\68ttp), line continuations, HTML entities (&#x68; &quot;), and treat a
// backslash as the slash browsers read it as, before looking for URLs, so encoded schemes and
// hosts cannot slip through. The page's Content-Security-Policy blocks remote loads anyway;
// these checks turn them into clear build errors instead of silent refusals.
const decodeCss = t => String(t).replace(/\\\r?\n/g, "").replace(/\\\\/g, "\u0000")
  .replace(/\\([0-9a-f]{1,6})\s?/gi, (_, h) => String.fromCodePoint(parseInt(h, 16))).replace(/\\(.)/g, "$1").replace(/\u0000/g, "\\");
const NAMED = { quot: '"', apos: "'", amp: "&", lt: "<", gt: ">", colon: ":", sol: "/", bsol: "\\", lpar: "(", rpar: ")", period: "." };
const decodeHtml = t => String(t).replace(/&#x([0-9a-f]+);?/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);?/g, (_, d) => String.fromCodePoint(Number(d))).replace(/&([a-z]+);/gi, (m, n) => NAMED[n.toLowerCase()] ?? m);
const stripComments = t => String(t).replace(/\/\*[\s\S]*?\*\//g, "");
const normalize = t => decodeCss(decodeHtml(stripComments(t))).replace(/\\/g, "/");
// Anything that names a scheme://, a scheme: with no slashes inside a resource string, a
// protocol-relative //host, or @import is remote. data: URIs are fine.
const REMOTE = /[a-z][a-z0-9+.-]*:\/\/|(["'(\s=,]|^)\/\/[^\/\s]|@import/i;
const hasRemote = t => REMOTE.test(normalize(t).replace(/data:[^"')]*/gi, ""));
// Every resource reference in CSS: url(...) arguments and the strings inside image-set().
function cssRefs(css) {
  const t = normalize(css), refs = [];
  for (const m of t.matchAll(/url\(\s*(['"]?)([^'")]*)\1\s*\)/gi)) refs.push(m[2].trim());
  for (const m of t.matchAll(/image-set\(([^)]*(\([^)]*\)[^)]*)*)\)/gi)) for (const q of m[1].matchAll(/(['"])(.*?)\1/g)) refs.push(q[2].trim());
  return refs;
}
const isLocalRef = r => !r || r.startsWith("#") || /^data:/i.test(r);
// Font families: HyperFrames fetches any family that has no @font-face from Google Fonts, so
// every named family must be generic or declared.
const GENERIC = new Set(["serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-serif", "ui-sans-serif", "ui-monospace",
  "ui-rounded", "math", "emoji", "fangsong", "inherit", "initial", "unset", "revert", "revert-layer"]);
const declaredFamilies = new Set(["ip montserrat", "ip inter"]);
for (const m of normalize(plan.css || "").matchAll(/@font-face\s*{[^}]*font-family\s*:\s*(['"]?)([^;'"}]+)\1/gi)) declaredFamilies.add(m[2].trim().toLowerCase());
// Custom properties declared in plan.css, so font-family: var(--brand) resolves like HyperFrames does.
const customProps = {};
for (const m of normalize(plan.css || "").matchAll(/(--[\w-]+)\s*:\s*([^;}]+)/g)) customProps[m[1]] = m[2].trim();
const resolveVars = (v, depth = 0) => depth > 5 ? v : v.replace(/var\(\s*(--[\w-]+)\s*(?:,\s*([^)]*))?\)/g, (_, n, fb) => resolveVars(customProps[n] ?? fb ?? "", depth + 1));
function undeclaredFamilies(text) {
  const own = {};
  for (const m of normalize(text).matchAll(/(--[\w-]+)\s*:\s*([^;}"'>]+)/g)) own[m[1]] = m[2].trim();
  const saved = { ...customProps };
  Object.assign(customProps, own);
  const t = resolveVars(normalize(text)), bad = [];
  for (const k of Object.keys(own)) if (k in saved) customProps[k] = saved[k]; else delete customProps[k];
  const lists = [...t.matchAll(/font-family\s*[:=]\s*(["']?)([^;}>]+?)\1\s*(?:[;}>/]|$|\s[\w:-]+=)/gim)].map(m => m[2]);
  for (const list of lists) for (const f of list.split(",")) {
    const name = f.trim().replace(/^['"]|['"]$/g, "").trim();
    if (name && !GENERIC.has(name.toLowerCase()) && !declaredFamilies.has(name.toLowerCase())) bad.push(name);
  }
  return [...new Set(bad)];
}
