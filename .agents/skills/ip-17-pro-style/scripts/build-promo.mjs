// Every timing value must be a finite number (durations positive) and every ease four numbers.
(function checkTiming(o, path) {
  for (const [k, v] of Object.entries(o)) {
    const at = `${path}.${k}`;
    if (/ease$|Ease$/.test(k)) { if (!(Array.isArray(v) && v.length === 4 && v.every(num))) fail(`${at} must be four numbers, like a CSS cubic-bezier.`); }
    else if (k === "bounce") { if (!(Array.isArray(v) && v.length === 2 && v.every(x => num(x) && x > 0))) fail(`${at} must be [restitution, power], two positive numbers.`); }
    else if (v && typeof v === "object") checkTiming(v, at);
    else if (!num(v)) fail(`${at} must be a number.`);
    else if (/duration|Duration|^up$|^down$|^tail$|^peak$/.test(k) && v <= 0) fail(`${at} must be greater than 0.`);
  }
})(T, "timing");
