function probeAudio(file) {
  const r = spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file], { encoding: "utf8" });
  const d = r.status === 0 ? Number(r.stdout.trim()) : NaN;
  if (!(d > 0)) { fail(`${relative(project, file)} has no playable audio (ffprobe reports no duration).`); done(); }
  return d;
}
function pngSize(file) {
  const fd = openSync(file, "r"), b = Buffer.alloc(24);
  readSync(fd, b, 0, 24, 0);
  closeSync(fd);
  if (b.toString("ascii", 12, 16) !== "IHDR") return null;
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

// Text measurement with the bundled fonts (fontkit ships with HyperFrames). Falls back to an
// average advance of 0.6 em when fontkit is unavailable.
let fontkit = null;
try { fontkit = require("fontkit"); } catch { warn("fontkit not found; line widths are estimated."); }
const FONTS = {
  montserrat: join(SKILL, "assets/fonts/Montserrat-Latin-VF.ttf"),
  inter: join(SKILL, "assets/fonts/Inter-Latin-VF.ttf"),
};
const fontCache = {};
function font(name) {
  if (!fontkit) return null;
  return (fontCache[name] ||= fontkit.openSync(FONTS[name]));
}
function measure(text, size, weight, name = "montserrat", tracking = 0) {
  const f = font(name);
  if (!f) return { width: String(text).length * size * 0.6, ascent: 0.968, descent: 0.251 };
  const v = f.getVariation({ wght: weight });
  const run = v.layout(String(text));
  const width = (run.advanceWidth / f.unitsPerEm) * size + tracking * size * Math.max(0, String(text).length - 1);
  return { width, ascent: f.ascent / f.unitsPerEm, descent: -f.descent / f.unitsPerEm };
}

