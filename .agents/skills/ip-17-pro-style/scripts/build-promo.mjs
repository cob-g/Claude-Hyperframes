#!/usr/bin/env node
// Build an "iPhone 17 Pro style" product promo as a HyperFrames composition from a plan file.
//
// Usage: node build-promo.mjs <project-dir> [--plan ip-plan.json] [--force]
//
// Writes <project>/index.html, the runtime kit in <project>/ip/ (including a three.js bundle),
// trimmed audio in <project>/ip/audio/, and DESIGN.md (regenerated on every build unless the
// project has a hand-written one, which is archived under <project>/archive/ instead).
// Everything is local: plan files must live inside the project, and nothing is fetched.
// Timings default to the values measured from the reference; see ../references/.

