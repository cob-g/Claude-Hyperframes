#!/usr/bin/env node
// Build a "cutout strobe" edit as a HyperFrames composition from a plan file.
//
// Usage: node .claude/skills/cutout-strobe/scripts/build-cutout.mjs <project-dir>
//          [--plan cs-plan.json] [--no-audio] [--no-matte] [--probe]
//
// The film is a chain of shots. In a "wall" the shot's subject is cut out and holds on top while a
// window cut into the shot behind it strobes through a montage of the other shots, one picture a
// frame. A "step" brings the next shot in over the current one as white shapes: a bar, a column, a
// disc, the next subject's silhouette. A flash is one white frame and thirteen frames of decay.
// Walls sit where the track's bass is in, steps where it rests, flashes on the backbeat.
//
// Writes <project>/index.html, the kit in <project>/cs/, graded proxies, mattes, montage stills,
// and whip stills in <project>/cs/media/, the premixed soundtrack in <project>/cs/audio/mix.wav
// (with stems), the cue sheet <project>/cs/cues.json, and DESIGN.md. A hand-written index.html or
// DESIGN.md is archived under <project>/archive/ first. Media work is cached in cs/cache/.
// --probe writes cs/probe/<clip>.png (three frames with a 10% grid) and, for every wall's clip,
// cs/probe/<clip>-cutout.png (the subject as the matte model sees it), then stops.
// See ../SKILL.md and ../references/plan-format.md.

