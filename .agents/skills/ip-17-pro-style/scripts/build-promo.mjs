// The first moment anything is on screen: a product's leading edge crossing the frame edge. The
// mirrored exit is empty again from mirror - firstInk.
function bezierAt(e, p) {
  const [x1, y1, x2, y2] = e;
  let lo = 0, hi = 1, s = p;
  for (let i = 0; i < 48; i++) {
    const x = 3 * (1 - s) ** 2 * s * x1 + 3 * (1 - s) * s * s * x2 + s ** 3;
    if (x < p) lo = s; else hi = s;
    s = (lo + hi) / 2;
  }
  return 3 * (1 - s) ** 2 * s * y1 + 3 * (1 - s) * s * s * y2 + s ** 3;
}
