function merge(a, b) {
  for (const [k, v] of Object.entries(b || {})) {
    if (Array.isArray(v) && v.length && Array.isArray(a[k]) && v.every(x => x && typeof x === "object" && !Array.isArray(x)))
      // Slot lists merge element by element; preset slots beyond the override stay.
      a[k] = Array.from({ length: Math.max(v.length, a[k].length) }, (_, i) => merge({ ...(a[k][i] || {}) }, v[i] || {}));
    else a[k] = v && typeof v === "object" && !Array.isArray(v) ? merge(a[k] || {}, v) : v;
  }
  return a;
}
