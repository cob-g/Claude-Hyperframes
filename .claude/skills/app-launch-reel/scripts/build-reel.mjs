// "*word*" marks emphasis; a line wrapped in "~...~" is a secondary (soft) line.
function wordsHtml(text, opts = {}) {
  const out = [];
  let inEm = false, count = 0;
  const tokens = String(text).split(/\s+/).filter(Boolean);
  const parts = [];
  for (let tok of tokens) {
    let open = false, close = false;
    if (tok.startsWith("*")) { open = true; tok = tok.slice(1); }
    if (tok.endsWith("*")) { close = true; tok = tok.slice(0, -1); }
    if (open) inEm = true;
    parts.push({ w: tok, em: inEm });
    if (close) inEm = false;
  }
  let i = 0;
  while (i < parts.length) {
    if (parts[i].em) {
      const run = [];
      while (i < parts.length && parts[i].em) run.push(parts[i++]);
      out.push(`<span class="alr-em${opts.emClass ?? " tint"}">${run.map(p => { count++; return `<span class="alr-w"><span class="alr-wi">${esc(p.w)}</span></span>`; }).join(" ")}${opts.underline ? UNDERLINE : ""}</span>`);
    } else {
      count++;
      out.push(`<span class="alr-w"><span class="alr-wi">${esc(parts[i++].w)}</span></span>`);
    }
  }
  return { html: out.join(" "), count };
}
function linesHtml(lines, cls, opts = {}) {
  let count = 0;
  const html = (Array.isArray(lines) ? lines : [lines]).map((ln, i, all) => {
    let s = String(ln), soft = false;
    if (/^~.*~$/.test(s)) { soft = true; s = s.slice(1, -1); }
    const underline = opts.underline && i === all.map(x => /\*/.test(x)).lastIndexOf(true);
    const w = wordsHtml(s, { underline, emClass: opts.emClass });
    count += w.count;
    return `<div class="alr-line${soft ? " soft" : ""} ${cls}">${w.html}</div>`;
  }).join("");
  return { html, count };
}
