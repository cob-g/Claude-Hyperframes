// Z order inside the window (low to high): shot videos, stills (bursts, freezes, plates), tiles,
// the film title, subject mattes (subject in front of the title), glows, cutouts.
const Z = { shot: 10, alt: 11, still: 300, tiles: 320, title: 500, matte: 600, glow: 650, cut: 700 };
