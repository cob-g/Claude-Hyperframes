const STEPS = ["bars", "top", "columns", "circle", "hero"];
const WHIPS = ["zoom", "spin", "v", "h"];
const EASES = {
  linear: t => t,
  // The reference's slit: fast at first, then slower, fitted to its measured height on 33 frames.
  expo: t => 1 - (Math.exp(-2 * t) - Math.exp(-2)) / (1 - Math.exp(-2)),
  out: t => 1 - Math.pow(1 - t, 3),
  in: t => t * t * t,
};
