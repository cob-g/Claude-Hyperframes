    // effects duck through sidechain compressors keyed by the voice. Each bus is also written
    // as a stem: the audit checks whoosh timing, the kick grid, and the voice on those.
    const isBed = l => /^\[f?m\d/.test(l);
    const bus = (ls, tag) => ls.length ? `${ls.join("")}amix=inputs=${ls.length}:normalize=0:duration=longest,apad=whole_dur=${D},atrim=0:${D}[${tag}]` : null;
