const measure = f => {
  const e = spawnSync("ffmpeg", ["-hide_banner", "-nostats", "-i", f, "-af", "ebur128=peak=true", "-f", "null", "-"], { encoding: "utf8" }).stderr;
  const num = re => Number(((e.match(re) || []).pop() || "").match(/-?[\d.]+/)?.[0]);
  return { I: num(/I:\s+-?[\d.]+ LUFS/g), TP: num(/Peak:\s+-?[\d.]+ dBFS/g) };
};
function analyze(file, span = []) {
  const r = spawnSync("ffmpeg", ["-v", "error", ...span, "-i", file, "-ac", "1", "-ar", "22050", "-f", "f32le", "-"], { maxBuffer: 1 << 29 });
  if (r.status !== 0) { fail(`ffmpeg could not decode ${rel(file)}`); return null; }
  const b = r.stdout, x = new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.length - (b.length % 4)));
  const hop = 220, n = Math.floor(x.length / hop), e = new Float64Array(n);
  let amp = 1e-6;
  for (let i = 0; i < n; i++) { let s = 0; for (let j = 0; j < hop; j++) { const v = x[i * hop + j]; s += v * v; if (Math.abs(v) > amp) amp = Math.abs(v); } e[i] = Math.sqrt(s / hop); }
  let pk = 0; for (let i = 1; i < n; i++) if (e[i] > e[pk]) pk = i;
  let on = 0; while (on < pk && e[on] < e[pk] * 0.1) on++;
  return { len: x.length / 22050, peak: pk / 100, onset: on / 100, amp, loud: e[pk] || 1e-6 };
}
