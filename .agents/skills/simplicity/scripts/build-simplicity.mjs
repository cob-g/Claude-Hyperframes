function analyze(file) {
  const r = spawnSync("ffmpeg", ["-v", "error", "-i", file, "-ac", "1", "-ar", "22050", "-f", "f32le", "-"], { maxBuffer: 1 << 29 });
  if (r.status !== 0) { fail(`ffmpeg could not decode ${rel(file)}`); return null; }
  const b = r.stdout, x = new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + b.length - (b.length % 4)));
  const hop = 220, n = Math.floor(x.length / hop), e = new Float64Array(n);
  for (let i = 0; i < n; i++) { let s = 0; for (let j = 0; j < hop; j++) { const v = x[i * hop + j]; s += v * v; } e[i] = Math.sqrt(s / hop); }
  let pk = 0; for (let i = 1; i < n; i++) if (e[i] > e[pk]) pk = i;
  let on = 0; while (on < pk && e[on] < e[pk] * 0.1) on++;
  return { len: x.length / 22050, peak: pk / 100, onset: on / 100 };
}
