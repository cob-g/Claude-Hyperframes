#!/usr/bin/env node
// Build a "negative strobe" edit as a HyperFrames composition from a plan file.
//
// Usage: node .claude/skills/negative-strobe/scripts/build-strobe.mjs <project-dir>
//          [--plan ns-plan.json] [--no-audio] [--probe]
//
// The output is a black-and-white film where every picture change is a hard, whole-frame switch:
// clips are cut into pieces of one to a few frames, each piece is graded to paper white and ink
// black, and neighbouring pieces flip between positive and negative. Nothing eases and nothing
// fades. Every piece is a still baked by ffmpeg, so a one-frame flash is exactly one frame.
//
// Writes <project>/index.html, the kit and font in <project>/ns/, the graded stills in
// <project>/ns/media/, the premixed soundtrack in <project>/ns/audio/mix.wav (with stems), the
// state and cue sheet <project>/ns/cues.json, and DESIGN.md. A hand-written index.html or
// DESIGN.md is archived under <project>/archive/ first. Media work is cached in ns/cache/.
// --probe writes three sheets per clip to ns/probe/ and stops: <clip>-frame.png (the source frame
// with a grid and the crop, for `focus`), <clip>.png (the grade at three pivots, for `pivot` and
// `bias`), and <clip>-strip.png (every third frame from the in point, for `at`).
// See ../SKILL.md and ../references/plan-format.md.

import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync, renameSync, cpSync, statSync, readdirSync, rmSync } from "node:fs";
import { join, resolve, dirname, relative, isAbsolute, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";

const SKILL = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const KIT_ROOT = resolve(SKILL, "../../..");
const GENERATED = "<!-- generated by negative-strobe/build-strobe.mjs -->";

const args = process.argv.slice(2);
if (!args.length || args.includes("--help")) {
  console.log("Usage: node build-strobe.mjs <project-dir> [--plan ns-plan.json] [--no-audio] [--probe]");
  process.exit(args.length ? 0 : 1);
}
const project = resolve(args[0]);
const planPath = resolve(project, args.includes("--plan") ? args[args.indexOf("--plan") + 1] : "ns-plan.json");
const noAudio = args.includes("--no-audio");
const probe = args.includes("--probe");

const errors = [], warnings = [];
const fail = m => errors.push(m);
const warn = m => warnings.push(m);
function done() {
  for (const w of warnings.splice(0)) console.warn(`warn: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`error: ${e}`);
    process.exit(1);
  }
}
if (!existsSync(planPath)) {
  console.error(`No plan at ${relative(process.cwd(), planPath)}. Start from .claude/skills/negative-strobe/templates/ns-plan.example.json.`);
  process.exit(1);
}
let plan;
try { plan = JSON.parse(readFileSync(planPath, "utf8")); } catch (e) { console.error(`${planPath}: ${e.message}`); process.exit(1); }

// ---------------------------------------------------------------- helpers
const r3 = n => Math.round(n * 1000) / 1000;
const r6 = n => Math.round(n * 1e6) / 1e6;
const esc = s => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const isInt = n => Number.isInteger(n);
const even = n => 2 * Math.round(n / 2);
const hash = (...parts) => createHash("sha1").update(parts.map(p => typeof p === "string" ? p : JSON.stringify(p)).join("|")).digest("hex").slice(0, 12);
function projectFile(p, where) {
  if (typeof p !== "string" || !p) { fail(`${where}: expected a file path inside the project.`); return null; }
  if (/^[a-z]+:/i.test(p)) { fail(`${where}: ${p} is a URL; download it into the project first.`); return null; }
  const abs = resolve(project, p);
  if (relative(project, abs).startsWith("..") || isAbsolute(relative(project, abs))) { fail(`${where}: ${p} is outside the project; copy or link it into assets/.`); return null; }
  if (!existsSync(abs)) { fail(`${where}: missing ${p}.`); return null; }
  return abs;
}
function run(cmd, argv, what, opts = {}) {
  const r = spawnSync(cmd, argv, { encoding: opts.binary ? null : "utf8", maxBuffer: 1 << 28, ...opts });
  if (r.status !== 0) {
    const err = (opts.binary ? String(r.stderr || "") : r.stderr || r.stdout || String(r.error || "")).slice(-900);
    fail(`${what} failed: ${err}`);
    done();
  }
  return r;
}
const probeDur = f => Number(spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], { encoding: "utf8" }).stdout.trim()) || 0;
const cycle = (arr, n) => Array.from({ length: n }, (_, k) => arr[k % arr.length]);
const pick = (v, k, fallback) => Array.isArray(v) ? (v[Math.min(k, v.length - 1)] ?? fallback) : (v ?? fallback);

// ---------------------------------------------------------------- canvas and look
const FPS = Number(plan.fps) || 24;
if (![24, 25, 30].includes(FPS)) fail(`fps must be 24, 25, or 30 (got ${plan.fps}). The style is measured at 24.`);
const FORMATS = { portrait: [1080, 1920], landscape: [1920, 1080], square: [1080, 1080] };
const FORMAT = plan.format || "portrait";
if (!FORMATS[FORMAT]) fail(`format must be one of ${Object.keys(FORMATS).join(", ")}.`);
const [W, H] = FORMATS[FORMAT] || FORMATS.portrait;
const sec = fr => r6(fr / FPS);

// The grade maps luma through a smooth step centred on the clip's pivot. `band` is the width of
// the step as a share of the tonal range: everything below it is ink, everything above is paper.
//   stamp: a near threshold, two tones (a stencil or a photocopy)
//   ink:   the reference's exaggerated S-curve, blown highlights and crushed shadows
//   soft:  a plain black-and-white frame, the breath between hard ones
const look = plan.look || {};
const BANDS = { stamp: 0.06, ink: 0.3, soft: 0.8, ...(look.bands || {}) };
for (const [k, v] of Object.entries(BANDS)) if (!(v > 0 && v <= 1)) fail(`look.bands.${k} must be between 0 and 1.`);
const DEFAULT_GRADE = look.grade ?? "ink";
if (!BANDS[DEFAULT_GRADE]) fail(`look.grade must be one of ${Object.keys(BANDS).join(", ")}.`);
const GRAIN = Number(look.grain ?? 9);
const SEED = Number(look.seed ?? 7);
const BLUR = Number(look.blur ?? 16);
if (look.paper || look.ink || look.tint) warn("look.paper / look.ink / look.tint are ignored: the style is neutral black and white.");

// Pattern letters, one per piece.
const TOKENS = {
  P: { neg: false }, N: { neg: true },
  G: { grade: "soft", neg: false }, g: { grade: "soft", neg: true },
  T: { grade: "stamp", neg: false }, t: { grade: "stamp", neg: true },
  K: { blank: "black" }, W: { blank: "white" },
};
function tokensOf(pattern, where, allowed = "PNGgTtKW") {
  const s = String(pattern ?? "");
  if (!s.length) { fail(`${where}.pattern is empty.`); return ["P"]; }
  const bad = [...s].filter(ch => !allowed.includes(ch));
  if (bad.length) { fail(`${where}.pattern "${s}": unknown letter ${[...new Set(bad)].join(", ")} (use ${[...allowed].join(" ")}).`); return ["P"]; }
  return [...s];
}

// ---------------------------------------------------------------- beat grid
// music.grid { bpm, downbeat } with the downbeat in file seconds. Reel time t plays file time
// music.start + t. Grid units are in beats.
const music = plan.music || {};
const M0 = Number(music.start) || 0;
const GRID = music.grid ? { beat: 60 / Number(music.grid.bpm), down: Number(music.grid.downbeat) || 0, bar: Number(music.grid.beats) || 4 } : null;
if (GRID && !(GRID.beat > 0)) fail("music.grid needs bpm (and downbeat, in file seconds).");
const UNITS = { "16th": 1 / 4, "8th": 1 / 2, beat: 1, bar: GRID?.bar ?? 4 };
const gridK = (t, unit) => (M0 + t - GRID.down) / (GRID.beat * unit);
const gridT = (k, unit) => GRID.down + k * GRID.beat * unit - M0;
const gridNear = (t, unit) => gridT(Math.round(gridK(t, unit)), unit);
const gridNext = (t, unit) => gridT(Math.ceil(gridK(t, unit) - 1e-6), unit);

// ---------------------------------------------------------------- clips
const clips = {};
if (!plan.clips || typeof plan.clips !== "object" || !Object.keys(plan.clips).length) fail("clips must name at least one source.");
for (const [name, c] of Object.entries(plan.clips || {})) {
  const where = `clips.${name}`;
  if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) fail(`${where}: clip names are lowercase letters, digits, and dashes.`);
  const o = { name, where, src: c.src, abs: projectFile(c.src, `${where}.src`), in: Number(c.in) || 0, zoom: Number(c.zoom) || 1, focus: c.focus || [0.5, 0.5], pivot: c.pivot ?? "auto", bias: Number(c.bias) || 0, crop: c.crop || null, grade: c.grade ?? null, offs: new Set() };
  if (o.grade && !BANDS[o.grade]) fail(`${where}.grade must be one of ${Object.keys(BANDS).join(", ")}.`);
  if (o.zoom < 1) fail(`${where}.zoom must be 1 or more.`);
  if (!Array.isArray(o.focus) || o.focus.length !== 2 || o.focus.some(v => !(v >= 0 && v <= 1))) fail(`${where}.focus must be [x, y], each 0-1 (the part of the frame the crop keeps).`);
  if (o.crop && (!Array.isArray(o.crop) || o.crop.length !== 4 || o.crop.some(v => !(Number(v) >= 0 && Number(v) <= 1)))) fail(`${where}.crop must be [x, y, w, h] fractions of the source frame.`);
  if (o.pivot !== "auto" && !(Number(o.pivot) > 0 && Number(o.pivot) < 1)) fail(`${where}.pivot must be "auto" or a number between 0 and 1.`);
  clips[name] = o;
}
if (!Array.isArray(plan.timeline) || !plan.timeline.length) fail("timeline must be a non-empty array.");
done();

// ---------------------------------------------------------------- timeline -> pieces (all in frames)
// A piece is one state of the picture: a still of one source frame in one grade and polarity, a
// black or white frame, or a type card. Each clip keeps a cursor, so the next time it is used the
// action has moved on.
const pieces = [], items = [];
const clipCursor = {};
let cursor = 0;
function clipRun({ name, tokens, dur, step, grade, at, punch, shift, blur, where, item, group }) {
  const c = clips[name];
  if (!c) { fail(`${where}: no clip named "${name}" (clips: ${Object.keys(clips).join(", ")}).`); return; }
  grade ??= c.grade ?? DEFAULT_GRADE;
  if (!BANDS[grade]) { fail(`${where}.grade must be one of ${Object.keys(BANDS).join(", ")}.`); return; }
  if (!isInt(step) || step < 0) { fail(`${where}.step must be a whole number of frames, 0 or more.`); return; }
  if (at != null) {
    if (!isInt(at) || at < 0) { fail(`${where}.at must be a whole number of frames after the clip's in point.`); return; }
    clipCursor[name] = at;
  }
  const off0 = clipCursor[name] ?? 0;
  let j = 0;
  tokens.forEach((tk, k) => {
    const T = TOKENS[tk], frames = dur[k];
    if (!isInt(frames) || frames < 1) { fail(`${where}: every piece lasts a whole number of frames, 1 or more.`); return; }
    if (T.blank) {
      pieces.push({ kind: T.blank, frame: cursor, frames, item, group, token: tk });
    } else {
      const sh = shift ? pick(shift, j, [0, 0]) : [0, 0];
      const need = 1 + 2 * Math.max(Math.abs(sh[0]), Math.abs(sh[1])) / 100;
      const scale = Math.max(typeof punch === "number" ? 1 + punch * j : Number(pick(punch, j, 1)), need);
      const off = off0 + j * step;
      c.offs.add(off);
      pieces.push({ kind: "still", frame: cursor, frames, clip: name, off, grade: T.grade || grade, neg: !!T.neg, token: tk, scale: r3(scale), shift: sh, blur: Number(Array.isArray(blur) ? (blur[j] ?? 0) : (blur ?? 0)), item, group });
      j++;
    }
    cursor += frames;
  });
  if (j && step > 0) clipCursor[name] = off0 + j * step;
}
plan.timeline.forEach((it, i) => {
  const where = `timeline[${i}]`;
  const item = { n: i + 1, where, start: cursor, label: it.label ?? null, sound: it.sound !== false, cue: it.cue ?? null, rise: !!it.rise, first: pieces.length };
  const eachOf = (n, d = 1) => { const e = it.each ?? d; return Array.from({ length: n }, (_, k) => Number(pick(e, k, d))); };
  const blurOf = () => it.blurIn ? Array.from({ length: Number(it.blurIn) }, (_, k) => r3(BLUR * (Number(it.blurIn) - k) / Number(it.blurIn))) : it.blur;
  if (it.black != null || it.white != null) {
    const kind = it.black != null ? "black" : "white";
    const n = Number(it[kind]);
    if (!isInt(n) || n < 1) fail(`${where}.${kind} must be a whole number of frames.`);
    item.kind = kind;
    pieces.push({ kind, frame: cursor, frames: n || 1, item: i, mute: !!it.mute, token: kind === "black" ? "K" : "W" });
    cursor += n || 1;
  } else if (it.card != null) {
    item.kind = "card";
    let toks = tokensOf(it.pattern ?? "P", where, "PNKW");
    const e = Number(pick(it.each, 0, 1));
    if (it.frames != null) toks = cycle(toks, Math.ceil(Number(it.frames) / e));
    const dur = eachOf(toks.length);
    if (it.frames != null) dur[dur.length - 1] -= dur.reduce((a, b) => a + b, 0) - Number(it.frames);
    toks.forEach((tk, k) => {
      const T = TOKENS[tk];
      if (!isInt(dur[k]) || dur[k] < 1) { fail(`${where}: every piece lasts a whole number of frames, 1 or more.`); return; }
      pieces.push(T.blank ? { kind: T.blank, frame: cursor, frames: dur[k], item: i, token: tk } : { kind: "card", frame: cursor, frames: dur[k], text: String(it.card), sub: it.sub ?? null, size: it.size ?? null, neg: !!T.neg, token: tk, item: i });
      cursor += dur[k];
    });
  } else if (it.burst) {
    // The tutorial's unit: every clip gives `pieces` one-frame pieces, `step` source frames apart,
    // flipping polarity piece by piece.
    if (!Array.isArray(it.burst) || !it.burst.length) fail(`${where}.burst: expected a list of clip names.`);
    item.kind = "burst";
    item.groups = [];
    const refs = (it.burst || []).map(r => typeof r === "string" ? { clip: r } : r);
    const pat = tokensOf(it.pattern ?? "PN", where);
    let bounds = null;
    if (it.on === "grid") {
      // One clip per grid step: each group starts on the whole frame nearest its step.
      if (!GRID) fail(`${where}.on "grid" needs music.grid { bpm, downbeat }.`);
      else {
        const unit = 1 / (Number(it.div) || 4);
        let t0 = gridNear(sec(cursor), unit);
        if (Math.abs(t0 - sec(cursor)) * FPS > 0.75) { warn(`${where}: the burst starts at frame ${cursor}, ${r3((sec(cursor) - t0) * 1000)} ms off the grid. End the item before it with "to" so it lands on a step.`); t0 = sec(cursor); }
        bounds = refs.map((_, k) => Math.round((t0 + k * GRID.beat * unit) * FPS));
        bounds.push(Math.round((t0 + refs.length * GRID.beat * unit) * FPS));
        bounds[0] = cursor;
        for (let k = 1; k < bounds.length; k++) bounds[k] = Math.max(bounds[k], bounds[k - 1] + 1);
      }
    }
    refs.forEach((r, k) => {
      const rw = `${where}.burst[${k}]`;
      const n = bounds ? bounds[k + 1] - bounds[k] : Number(r.pieces ?? it.pieces ?? 3);
      if (!isInt(n) || n < 1) { fail(`${rw}.pieces must be a whole number, 1 or more.`); return; }
      const toks = cycle(r.pattern ? tokensOf(r.pattern, rw) : pat, n);
      item.groups.push({ frame: cursor, clip: r.clip });
      clipRun({ name: r.clip, tokens: toks, dur: bounds ? toks.map(() => 1) : eachOf(n), step: Number(r.step ?? it.step ?? 3), grade: r.grade ?? it.grade, at: r.at, punch: r.punch ?? it.punch, shift: r.shift ?? it.shift, blur: r.blur ?? it.blur, where: rw, item: i, group: k });
    });
  } else if (it.clip) {
    item.kind = "clip";
    let toks = tokensOf(it.pattern ?? "P", where);
    const e = Number(pick(it.each, 0, 1));
    if (it.frames != null) {
      if (!isInt(Number(it.frames)) || Number(it.frames) < 1) fail(`${where}.frames must be a whole number of frames.`);
      toks = cycle(toks, Math.ceil(Number(it.frames) / e));
    }
    const dur = eachOf(toks.length);
    if (it.frames != null) dur[dur.length - 1] -= dur.reduce((a, b) => a + b, 0) - Number(it.frames);
    // "to": the pattern keeps cycling until the next grid line, so what follows lands on the beat.
    // Whole pieces are added; frames left over go to the last one.
    if (it.to != null && GRID && UNITS[it.to]) {
      const pat = tokensOf(it.pattern ?? "P", where), end = cursor + dur.reduce((a, b) => a + b, 0);
      let extra = Math.round(gridNext(sec(end) - 0.5 / FPS, UNITS[it.to]) * FPS) - end;
      for (let k = toks.length; extra >= dur[dur.length - 1]; k++) { toks.push(pat[k % pat.length]); dur.push(dur[dur.length - 1]); extra -= dur[dur.length - 1]; }
      if (extra > 0) dur[dur.length - 1] += extra;
    }
    clipRun({ name: it.clip, tokens: toks, dur, step: Number(it.step ?? 3), grade: it.grade, at: it.at, punch: it.punch, shift: it.shift, blur: blurOf(), where, item: i, group: 0 });
  } else fail(`${where}: expected "clip", "burst", "card", "black", or "white".`);
  // "to" on a card, a blank, or a burst holds its last piece until the next grid line. (A clip
  // item has already cycled its pattern up to the line.)
  if (it.to != null && pieces.length > item.first) {
    if (!GRID) fail(`${where}.to needs music.grid { bpm, downbeat }.`);
    else if (!UNITS[it.to]) fail(`${where}.to must be one of ${Object.keys(UNITS).join(", ")}.`);
    else {
      const target = Math.round(gridNext(sec(cursor) - 0.5 / FPS, UNITS[it.to]) * FPS);
      if (target > cursor) { pieces[pieces.length - 1].frames += target - cursor; cursor = target; }
    }
  }
  item.end = cursor;
  item.last = pieces.length;
  items.push(item);
});
const TOTAL = cursor;
const D = sec(TOTAL);
done();
if (TOTAL < FPS) warn(`The film is ${r3(D)} s: that is a transition, not a reel. Cut the render into another edit, or add holds around the burst (see SKILL.md).`);
const stills = pieces.filter(p => p.kind === "still");
if (stills.length > 400) warn(`${stills.length} stills: long real-time runs ("step": 1) are heavy. Hold frames with "each" or freeze with "step": 0 where the action allows.`);

// ---------------------------------------------------------------- media prep
const nsDir = join(project, "ns");
const mediaDir = join(nsDir, "media");
const cacheDir = join(nsDir, "cache");
mkdirSync(mediaDir, { recursive: true });
mkdirSync(cacheDir, { recursive: true });
const manifestPath = join(cacheDir, "manifest.json");
