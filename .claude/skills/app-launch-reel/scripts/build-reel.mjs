      if (end > D - 0.3) warn(`${ln.where} runs to ${r3(end)} s; end the voice before the last 0.3 s so the reel rings out.`);
      const gdb = Number.isFinite(ln.I) ? Math.max(-24, Math.min(24, level - ln.I)) : 0;
      const g = Math.pow(10, gdb / 20) * vgain * (ln.gain ?? 1);
      const k = add(ln.abs);
