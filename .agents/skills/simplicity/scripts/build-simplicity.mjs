#!/usr/bin/env node
// Build a "simplicity" edit as a HyperFrames composition from a plan file.
//
// Usage: node .claude/skills/simplicity/scripts/build-simplicity.mjs <project-dir>
//          [--plan simp-plan.json] [--no-audio] [--no-matte] [--probe]
//
// The output is the film alone, full frame at 1920x1080: a fast, cream-graded cut at 24 fps with
// frame-level effects (one-frame clips, subject glow hops, stutters, cutout pre-reveals, tile
// mosaics, teleports, freezes) and a persistent extended-type film title that can sit behind the
// subject, over a song-led mix. Every time is a whole frame at plan.fps.
//
// Writes <project>/index.html, the kit and font in <project>/simp/, graded proxies, stills, masks,
// and mattes in <project>/simp/media/, the premixed soundtrack in <project>/simp/audio/mix.wav
// (with stems), the cue sheet <project>/simp/cues.json, and DESIGN.md. A hand-written index.html
// or DESIGN.md is archived under <project>/archive/ first. Media work is cached in simp/cache/.
// --probe writes simp/probe/shot-NN.png (first, middle, last frame with a 10% grid) for picking
// glow spots, then stops. See ../SKILL.md and ../references/plan-format.md.

import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync, renameSync, cpSync, statSync, readdirSync, rmSync } from "node:fs";
import { join, resolve, dirname, relative, isAbsolute, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";

const SKILL = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const KIT_ROOT = resolve(SKILL, "../../..");
const GENERATED = "<!-- generated by simplicity/build-simplicity.mjs -->";

const args = process.argv.slice(2);
if (!args.length || args.includes("--help")) {
  console.log("Usage: node build-simplicity.mjs <project-dir> [--plan simp-plan.json] [--no-audio] [--no-matte] [--probe]");
  process.exit(args.length ? 0 : 1);
}
const project = resolve(args[0]);
const planPath = resolve(project, args.includes("--plan") ? args[args.indexOf("--plan") + 1] : "simp-plan.json");
const noAudio = args.includes("--no-audio");
const noMatte = args.includes("--no-matte");
const probe = args.includes("--probe");

const errors = [], warnings = [];
const fail = m => errors.push(m);
const warn = m => warnings.push(m);
function done() {
  for (const w of warnings.splice(0)) console.warn(`warn: ${w}`);
  if (errors.length) {
    for (const e of errors) console.error(`error: ${e}`);
    process.exit(1);
  }
}
if (!existsSync(planPath)) {
  console.error(`No plan at ${relative(process.cwd(), planPath)}. Start from .claude/skills/simplicity/templates/simp-plan.example.json.`);
  process.exit(1);
}
let plan;
try { plan = JSON.parse(readFileSync(planPath, "utf8")); } catch (e) { console.error(`${planPath}: ${e.message}`); process.exit(1); }

// ---------------------------------------------------------------- helpers
const r3 = n => Math.round(n * 1000) / 1000;
const r6 = n => Math.round(n * 1e6) / 1e6;
const esc = s => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const HEX = /^#[0-9a-fA-F]{6}$/;
const color = (v, where, fallback) => {
  if (v == null) return fallback;
  if (!HEX.test(v)) { fail(`${where}: colours must be #rrggbb (got ${JSON.stringify(v)}).`); return fallback; }
  return v;
};
const isInt = n => Number.isInteger(n);
const hash = (...parts) => createHash("sha1").update(parts.map(p => typeof p === "string" ? p : JSON.stringify(p)).join("|")).digest("hex").slice(0, 12);
function projectFile(p, where) {
  if (typeof p !== "string" || !p) { fail(`${where}: expected a file path inside the project.`); return null; }
  if (/^[a-z]+:/i.test(p)) { fail(`${where}: ${p} is a URL; download it into the project first.`); return null; }
  const abs = resolve(project, p);
  if (relative(project, abs).startsWith("..") || isAbsolute(relative(project, abs))) { fail(`${where}: ${p} is outside the project; copy or link it into assets/.`); return null; }
  if (!existsSync(abs)) { fail(`${where}: missing ${p}.`); return null; }
  return abs;
}
function run(cmd, argv, what, opts = {}) {
  const r = spawnSync(cmd, argv, { encoding: opts.binary ? null : "utf8", maxBuffer: 1 << 28, ...opts });
  if (r.status !== 0) {
    const err = (opts.binary ? String(r.stderr || "") : r.stderr || r.stdout || String(r.error || "")).slice(-900);
    fail(`${what} failed: ${err}`);
    done();
  }
  return r;
}
const probeDur = f => Number(spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], { encoding: "utf8" }).stdout.trim()) || 0;
// A seeded PRNG (mulberry32): every "random" pattern is fixed by the plan's seed.
function prng(seed) {
  let a = seed >>> 0;
  return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

// ---------------------------------------------------------------- canvas and look
const FPS = Number(plan.fps) || 24;
if (![24, 25, 30].includes(FPS)) fail(`fps must be 24, 25, or 30 (got ${plan.fps}). The style is measured at 24.`);
// The film, full frame. Sizes measured in the reference's 912 px wide film scale by U.
const W = 1920, H = 1080, U = W / 912;
const PW = 1920, PH = 1080; // proxy size
const MW = 1280, MH = 720;  // matte size: remove-background runs on a 1280x720 copy; the page scales it up
const sec = fr => r6(fr / FPS);
// Clip timing for media: the start rounds down and the end rounds up to the microsecond, so a clip
// always covers its first and last frame. Rounding both to nearest can leave a 1 µs gap between two
// shots, and a renderer sampling exactly frame/fps then shows a black frame at that cut.
const clipTime = (fr, frames) => {
  const start = Math.floor((fr / FPS) * 1e6) / 1e6;
  const dur = Math.ceil(((fr + frames) / FPS - start) * 1e6) / 1e6;
  return `data-start="${start}" data-duration="${dur}"`;
};
const film = plan.film || {};
if (plan.frame) warn("plan.frame is ignored: this skill renders the film only (no sheet, label line, timeline panel, or credits).");
const P = {
  ink: color(film.title?.dark, "film.title.dark", "#0a0a0a"),
  titleInk: color(film.title?.color, "film.title.color", "#ffffff"),
};

// Grades are ffmpeg filters baked into the proxies, so every still, cutout, and tile matches the
// footage frame for frame. "cream" is the reference look: contrast, rich colour, cream highlights,
// cool shadows, crushed blacks.
const GRADES = {
  cream: "eq=contrast=1.22:saturation=1.42:gamma=0.97,colorbalance=rs=-0.07:bs=0.05:rh=0.06:gh=0.04:bh=-0.10,curves=all='0/0 0.08/0.03 0.5/0.52 0.9/0.95 1/1'",
  clean: "eq=contrast=1.1:saturation=1.15",
  // For footage that is already graded (a music video): the same cream-and-cool tilt, much lighter.
  soft: "eq=contrast=1.08:saturation=1.06:gamma=0.99,colorbalance=rs=-0.04:bs=0.03:rh=0.05:gh=0.035:bh=-0.07,curves=all='0/0 0.06/0.025 0.5/0.51 0.92/0.955 1/1'",
  none: "",
};
let gradeName = typeof film.grade === "string" ? film.grade : film.grade?.filter ? "custom" : "cream";
const GRADE = film.grade?.filter ?? GRADES[gradeName];
if (GRADE == null) fail(`film.grade must be one of ${Object.keys(GRADES).join(", ")} or { "filter": "<ffmpeg filter>" }.`);
const EXPOSURE = film.exposure ?? "auto";
// A cropped shot is scaled up to fill the frame; a light luma-only unsharp mask brings back the
// edge detail the upscale softens. film.sharpen sets the amount (0 turns it off).
const SHARPEN = Number(film.sharpen ?? 0.4);

// Crops: [x, y, w, h] fractions of the source frame, applied before the grade. Use them to cut a
// baked-in border (a film-frame overlay, letterboxing) out of footage. film.crops names presets;
// film.crop is the default for every shot.
const CROPS = { ...(film.crops || {}) };
function cropOf(v, where) {
  if (v == null || v === false) return null;
  const c = typeof v === "string" ? CROPS[v] : v;
  if (!Array.isArray(c) || c.length !== 4 || c.some(n => !(Number(n) >= 0 && Number(n) <= 1)) || c[0] + c[2] > 1.0001 || c[1] + c[3] > 1.0001) {
    fail(`${where}: crop must be [x, y, w, h] fractions of the source frame, or a name from film.crops (${Object.keys(CROPS).join(", ") || "none defined"}).`);
    return null;
  }
  return c.map(Number);
}

// ---------------------------------------------------------------- song map
// The song is one span from music.start, or music.segments: spans of the file played back to back
// (a chorus cut to length on its bar lines) and joined with a short crossfade. songAt(t) maps reel
// time to file time; lip-synced shots ("sync") read their in point from it.
const music = plan.music || {};
const SEGMENTS = [];
if (music.file) {
  if (Array.isArray(music.segments) && music.segments.length) {
    let at = 0;
    music.segments.forEach((sg, i) => {
      const from = Number(sg.from), to = Number(sg.to);
      if (!(from >= 0) || !(to > from)) fail(`music.segments[${i}]: give "from" and "to" in seconds of the file, "to" after "from".`);
      SEGMENTS.push({ from, to, at, len: to - from });
      at += to - from;
    });
  } else SEGMENTS.push({ from: Number(music.start) || 0, to: Infinity, at: 0, len: Infinity });
}
const segIndexAt = t => { let k = 0; SEGMENTS.forEach((g, i) => { if (t >= g.at - 1e-9) k = i; }); return k; };
const songAt = t => { const g = SEGMENTS[segIndexAt(t)]; return g ? g.from + (t - g.at) : null; };

// The song's beat grid: music.grid { bpm, downbeat } with the downbeat in file seconds, measured
// from real kick attacks (see references/music-video.md). Beat-synced effects read it.
const GRID = music.grid ? { beat: 60 / Number(music.grid.bpm), down: Number(music.grid.downbeat) } : null;
if (GRID && !(GRID.beat > 0 && GRID.down >= 0)) fail("music.grid needs bpm and downbeat (file seconds).");
// Grid position of a reel time, in steps of 1/div beat (4 = sixteenths, 8 = thirty-seconds).
const gridPos = (reelT, div) => (songAt(reelT) - GRID.down) / (GRID.beat / div);
// A grid tile build lands one tile per step, accelerating into the cut: thirty-seconds through the
// last beat, sixteenths before it. Returns ascending reel frames; the cut itself is the downbeat.
function buildSteps(cutFrame, count) {
  const cutT = cutFrame / FPS, t32 = GRID.beat / 8, t16 = GRID.beat / 4;
  const times = [];
  for (let j = 1; j <= Math.min(count, 8); j++) times.push(cutT - j * t32);
  for (let j = 1; times.length < count; j++) times.push(cutT - GRID.beat - j * t16);
  const frames = times.map(t => Math.round(t * FPS)).sort((a, b) => a - b);
  return frames.filter((f, i) => i === 0 || f > frames[i - 1]);
}

// ---------------------------------------------------------------- shots and fx (all in frames)
const EXITS = ["cut", "cutout", "tiles", "stutter"];
const FX = ["glow", "stutter", "teleport", "freeze"];
if (!Array.isArray(plan.shots) || !plan.shots.length) fail("shots must be a non-empty array.");
done();

const shots = [];
let cursor = 0;
plan.shots.forEach((s, i) => {
  const where = `shots[${i}]`;
  const n = i + 1;
  const sh = { n, id: `sh-${n}`, where, label: s.label ?? null, labelLead: Number(s.labelLead) || 0, fx: [], exit: null };
  if (s.burst) {
    if (!Array.isArray(s.burst) || !s.burst.length) fail(`${where}.burst: expected a list of { "src", "in" }.`);
    sh.kind = "burst";
    sh.each = Number(s.each) || 2;
    if (!isInt(sh.each) || sh.each < 1) fail(`${where}.each must be a whole number of frames.`);
    sh.items = (s.burst || []).map((b, k) => ({ abs: projectFile(b.src, `${where}.burst[${k}].src`), src: b.src, in: Number(b.in) || 0, exposure: b.exposure ?? s.exposure ?? EXPOSURE, crop: cropOf(b.crop !== undefined ? b.crop : s.crop !== undefined ? s.crop : film.crop, `${where}.burst[${k}].crop`) }));
    sh.frames = sh.items.length * sh.each;
  } else {
    sh.kind = "video";
    sh.abs = projectFile(s.src, `${where}.src`);
    sh.src = s.src;
    sh.in = Number(s.in) || 0;
    sh.frames = s.frames;
    sh.exposure = s.exposure ?? EXPOSURE;
    sh.crop = cropOf(s.crop !== undefined ? s.crop : film.crop, `${where}.crop`);
    sh.name = s.name ?? null;
    sh.behind = s.behind ?? film.behind ?? false;
    if (!isInt(sh.frames) || sh.frames < 1) fail(`${where}.frames must be a whole number of frames (at ${FPS} fps).`);
  }
  sh.start = cursor;
  sh.end = cursor + (sh.frames || 0);
  cursor = sh.end;
  // Lip sync: the shot's in point is the song's time at its first frame, plus `sync` seconds. With
  // footage cut to the same song (a music video), 0 keeps the performance in sync; a repeated
  // chorus lends its takes with the offset between the choruses.
  if (s.sync != null && sh.kind === "video") {
    if (!SEGMENTS.length) fail(`${where}.sync needs music.file.`);
    else {
      sh.sync = Number(s.sync);
      sh.in = r6(songAt(sec(sh.start)) + sh.sync);
      if (segIndexAt(sec(sh.start)) !== segIndexAt(sec(sh.end - 1))) warn(`${where}: this synced shot crosses a song join at ${r3(SEGMENTS[segIndexAt(sec(sh.end - 1))].at)} s, so it drifts out of sync after it. Cut there.`);
    }
  }
  // exit into the next shot
  const ex = typeof s.exit === "string" ? { type: s.exit } : (s.exit || { type: "cut" });
  if (!EXITS.includes(ex.type)) fail(`${where}.exit.type must be one of ${EXITS.join(", ")}.`);
  ex.frames = ex.type === "cut" ? 0 : Number(ex.frames ?? { cutout: 2, tiles: 18, stutter: 5 }[ex.type]);
  // "on": "grid" tiles build on the song's beat grid into a cut that sits on a beat.
  if (ex.type === "tiles" && ex.on === "grid") {
    if (!GRID) fail(`${where}.exit.on "grid" needs music.grid { bpm, downbeat }.`);
    else {
      const off = gridPos(sec(sh.end), 4);
      if (Math.abs(off - Math.round(off)) * (GRID.beat / 4) * FPS > 0.75) warn(`${where}: the tile build lands at frame ${sh.end}, ${r3((off - Math.round(off)) * GRID.beat / 4 * 1000)} ms off the nearest sixteenth. Move the cut onto the grid.`);
      ex.steps = buildSteps(sh.end, (Number(ex.cols) || 4) * (Number(ex.rows) || 3));
      ex.frames = sh.end - ex.steps[0];
    }
  }
  if (!isInt(ex.frames) || ex.frames < 0) fail(`${where}.exit.frames must be a whole number.`);
  if (ex.frames > (sh.frames || 0)) fail(`${where}.exit.frames (${ex.frames}) is longer than the shot.`);
  ex.at = sh.end - ex.frames;
  sh.exit = ex;
  if (ex.label) sh.exitLabel = ex.label;
  // in-shot fx
  (s.fx || []).forEach((fx, k) => {
    const fw = `${where}.fx[${k}]`;
    if (!FX.includes(fx.type)) { fail(`${fw}.type must be one of ${FX.join(", ")}.`); return; }
    if (sh.kind !== "video") { fail(`${fw}: effects need a video shot, not a burst.`); return; }
    const at = Number(fx.at ?? 0);
    if (!isInt(at) || at < 0 || at >= sh.frames) { fail(`${fw}.at must be a frame inside the shot (0-${sh.frames - 1}).`); return; }
    const o = { ...fx, at, where: fw };
    if (fx.type === "glow") {
      const each = Number(fx.each) || 2, gap = Number(fx.gap) || 0;
      let hops = fx.hops;
      if (!hops) hops = Array.from({ length: Number(fx.count) || 5 }, () => ({}));
      o.hops = hops.map((h, j) => ({ frames: Number(h.frames) || each, gap: Number(h.gap ?? gap), spot: h.spot || null, pick: h.pick ?? null, j }));
      o.frames = o.hops.reduce((a, h) => a + h.frames + h.gap, 0);
    } else if (fx.type === "stutter" || fx.type === "teleport") {
      o.frames = Number(fx.frames) || 5;
      if (fx.type === "stutter" && !fx.with) fail(`${fw}.with: give { "in": <seconds> } or { "sync": <offset> } (and optionally "src") for the other take.`);
      if (fx.type === "teleport" && !fx.plate) fail(`${fw}.plate: give { "in": <seconds> } for a clean plate of the same locked shot.`);
      o.settle = fx.settle || (fx.type === "stutter" ? "b" : "a");
    } else if (fx.type === "freeze") {
      o.frames = sh.frames - at;
    }
    if (at + o.frames > sh.frames) fail(`${fw} runs ${at + o.frames - sh.frames} frames past the end of the shot.`);
    sh.fx.push(o);
  });
  shots.push(sh);
});
const TOTAL = cursor;
const D = sec(TOTAL);
shots.forEach((sh, i) => {
  if (sh.exit.type !== "cut" && !shots[i + 1]) fail(`${sh.where}.exit: the last shot cannot transition; use "cut" and a freeze instead.`);
  if (sh.exit.type !== "cut" && shots[i + 1]?.kind !== "video") fail(`${sh.where}.exit.${sh.exit.type} needs a video shot next.`);
});
if (TOTAL < FPS * 4) warn(`The reel is ${r3(D)} s. The reference is 10.3 s; below 4 s the labels cannot be read.`);
done();

// ---------------------------------------------------------------- media prep
const simpDir = join(project, "simp");
const mediaDir = join(simpDir, "media");
const cacheDir = join(simpDir, "cache");
mkdirSync(mediaDir, { recursive: true });
mkdirSync(cacheDir, { recursive: true });
const manifestPath = join(cacheDir, "manifest.json");
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : {};
const used = new Set();
const saveManifest = () => writeFileSync(manifestPath, JSON.stringify(manifest, null, 1) + "\n");
const stamp = f => { const st = statSync(f); return `${st.size}:${Math.round(st.mtimeMs)}`; };
const rel = f => relative(project, f);
const cached = (key, out) => { used.add(rel(out)); return manifest[rel(out)] === key && existsSync(out); };
const remember = (key, out) => { manifest[rel(out)] = key; saveManifest(); };

// Exposure: "auto" lifts or lowers the mid-tones with a gamma curve so every shot lands near the
// same mean brightness before the grade; a number is a gamma (1.2 brightens, 0.85 darkens).
const exposureCache = {};
const cropVf = c => c ? `crop=w=iw*${c[2]}:h=ih*${c[3]}:x=iw*${c[0]}:y=ih*${c[1]}` : null;
function gammaFor(abs, t, exposure, crop) {
  if (typeof exposure === "number") return exposure;
  if (exposure === false || exposure === "none") return 1;
  const key = `${abs}@${r3(t)}@${crop}`;
  if (exposureCache[key]) return exposureCache[key];
  const vf = [cropVf(crop), "scale=64:36", "format=gray"].filter(Boolean).join(",");
  const r = spawnSync("ffmpeg", ["-v", "error", "-ss", String(Math.max(0, t)), "-i", abs, "-frames:v", "1", "-vf", vf, "-f", "rawvideo", "-"], { maxBuffer: 1 << 20 });
  const b = r.stdout || Buffer.alloc(0);
  let mean = 0.47;
  if (b.length) { let s = 0; for (const v of b) s += v; mean = s / b.length / 255; }
  // Lifting a dark shot is safe; darkening a bright one crushes a backlit subject, so "auto" only
  // darkens a little. Give a number to go further.
  const g = Math.max(0.92, Math.min(1.5, Math.log(Math.max(0.05, mean)) / Math.log(0.47)));
  exposureCache[key] = Math.abs(g - 1) < 0.06 ? 1 : Math.round(g * 100) / 100;
  return exposureCache[key];
}
function chain(gamma, crop) {
  const parts = [`fps=${FPS}`, cropVf(crop), `scale=${PW}:${PH}:force_original_aspect_ratio=increase:flags=lanczos`, `crop=${PW}:${PH}`].filter(Boolean);
  if (crop && SHARPEN > 0) parts.push(`unsharp=5:5:${SHARPEN}:5:5:0`);
  if (gamma !== 1) parts.push(`eq=gamma=${gamma}`);
  if (GRADE) parts.push(GRADE);
  parts.push("format=yuv420p");
  return parts.join(",");
}
// A proxy is the shot's source from `pre` frames before its in point to `post` frames after its
// out point, graded and at the plan's frame rate, with a keyframe every half second.
// Source frame rate, so in points snap to whole source frames: a seek that lands between two
// frames would otherwise start one frame late, and a one-frame flash of the neighbouring shot
// shows at a cut.
const fpsCache = {};
function srcFps(abs) {
  if (fpsCache[abs]) return fpsCache[abs];
  const r = spawnSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=r_frame_rate", "-of", "csv=p=0", abs], { encoding: "utf8" }).stdout.trim();
  const [a, b] = r.split("/").map(Number);
  return (fpsCache[abs] = a && b ? a / b : FPS);
}
const snap = (abs, t) => { const f = srcFps(abs); return Math.round(t * f) / f; };
// Seek a quarter frame early so the wanted frame is the first one decoded.
const seekAt = (abs, t) => Math.max(0, t - 0.25 / srcFps(abs));
function makeProxy(abs, inSec, frames, name, exposure, crop) {
  inSec = snap(abs, inSec);
  const srcDur = probeDur(abs);
  if (!srcDur) { fail(`cannot read ${rel(abs)}`); done(); }
  const pre = Math.min(12, Math.floor(inSec * FPS));
  const from = inSec - pre / FPS;
  const post = 12;
  const len = Math.min((pre + frames + post) / FPS, srcDur - from);
  if (inSec + frames / FPS > srcDur + 0.01) fail(`${rel(abs)} is ${r3(srcDur)} s; ${frames} frames from ${inSec} s run past its end.`);
  const gamma = gammaFor(abs, inSec + frames / FPS / 2, exposure, crop);
  const out = join(mediaDir, `${name}.mp4`);
  const vf = chain(gamma, crop);
  const key = hash(abs, stamp(abs), r6(from), r6(len), vf, "v4");
  if (!cached(key, out)) {
    run("ffmpeg", ["-v", "error", "-y", "-ss", String(r6(seekAt(abs, from))), "-t", String(r6(len)), "-i", abs, "-vf", vf, "-an",
      "-c:v", "libx264", "-preset", "medium", "-crf", "16", "-g", String(Math.round(FPS / 2)), "-keyint_min", String(Math.round(FPS / 2)),
      "-sc_threshold", "0", "-movflags", "+faststart", out], `proxy ${name}`);
    remember(key, out);
  }
  return { file: out, pre, gamma, key };
}
// A still is one exact frame of a proxy (so a cutout or tile matches the video frame it stands in
// for), or one graded frame of a source for the one-frame clips.
function stillFromProxy(px, frameIdx, name) {
  const out = join(mediaDir, `${name}.jpg`);
  const key = hash(px.key, frameIdx);
  if (!cached(key, out)) {
    run("ffmpeg", ["-v", "error", "-y", "-i", px.file, "-vf", `select=eq(n\\,${frameIdx})`, "-frames:v", "1", "-q:v", "2", out], `still ${name}`);
    remember(key, out);
  }
  return out;
}
function stillFromSource(abs, t, name, exposure, crop) {
  t = snap(abs, t);
  const out = join(mediaDir, `${name}.jpg`);
  const gamma = gammaFor(abs, t, exposure, crop);
  const vf = chain(gamma, crop).replace(`fps=${FPS},`, "");
  const key = hash(abs, stamp(abs), r6(t), vf, "s2");
  if (!cached(key, out)) {
    run("ffmpeg", ["-v", "error", "-y", "-ss", String(r6(seekAt(abs, t))), "-i", abs, "-frames:v", "1", "-vf", vf, "-q:v", "2", out], `still ${name}`);
    remember(key, out);
  }
  return out;
}
// Subject masks come from Apple Vision (scripts/simp-mask.swift), compiled once per project.
let maskBin = null;
function masks(still, name) {
  if (process.platform !== "darwin") { fail(`${name}: subject masks need macOS (Apple Vision). Use "spot" glows and skip cutouts elsewhere.`); done(); }
  if (!maskBin) {
    maskBin = join(cacheDir, "bin", "simp-mask");
    const src = join(SKILL, "scripts", "simp-mask.swift");
    const key = hash(stamp(src));
    if (!cached(key, maskBin)) {
      mkdirSync(dirname(maskBin), { recursive: true });
      run("swiftc", ["-O", src, "-o", maskBin], "compiling simp-mask.swift (needs Xcode command line tools)");
      remember(key, maskBin);
    }
  }
  const dir = join(mediaDir, `mask-${name}`);
  const info = join(dir, "info.json");
  const key = hash(stamp(still), "m2");
  used.add(rel(dir));
  if (!(manifest[rel(info)] === key && existsSync(info))) {
    rmSync(dir, { recursive: true, force: true });
    const r = run(maskBin, [still, dir], `masking ${name}`);
    writeFileSync(info, r.stdout.trim() + "\n");
    remember(key, info);
  }
  used.add(rel(info));
  const j = JSON.parse(readFileSync(info, "utf8"));
  j.dir = dir;
  return j;
}
function pickInstance(m, pick, where) {
  if (!m.instances.length) { fail(`${where}: Vision found no subject in this frame. Use a "spot" instead, or choose another frame.`); return null; }
  if (pick == null || pick === "largest" || pick === "all") return pick === "all" ? join(m.dir, "all.png") : join(m.dir, `inst-${m.instances[0].id}.png`);
  if (Number.isInteger(pick)) {
    const inst = m.instances[pick - 1];
    if (!inst) { fail(`${where}: pick ${pick}, but Vision found ${m.instances.length} subject(s) (1 = largest).`); return null; }
    return join(m.dir, `inst-${inst.id}.png`);
  }
  fail(`${where}.pick must be "largest", "all", or a 1-based rank by size.`);
  return null;
}

