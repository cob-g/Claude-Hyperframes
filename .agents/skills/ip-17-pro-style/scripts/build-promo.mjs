// Trimmed, faded copies in ip/audio/: `start` skips into the file (an intro, or silence before
// a hit), `length` keeps that many seconds, and `fade` ramps the end out. `loudness` then sets
// one static gain toward `I` LUFS and runs a lookahead limiter whose ceiling is `ceiling` dBFS.
// Downloaded masters are often brick-walled near 0 dBFS, and HyperFrames' 188 kbps AAC encode
// overshoots such transients by up to 4 dB; a sub-bass high-pass and a ceiling well below full
// scale keep the delivered true peak under -1 dBTP. The limiter only touches isolated peaks.
function loudnessOf(file) {
  const r = spawnSync("ffmpeg", ["-hide_banner", "-nostats", "-i", file, "-af", "ebur128=peak=true", "-f", "null", "-"], { encoding: "utf8" });
  const I = Number((r.stderr.match(/I:\s+(-?[\d.]+) LUFS/g) || []).pop()?.match(/-?[\d.]+/)[0]);
  const TP = Number((r.stderr.match(/Peak:\s+(-?[\d.]+) dBFS/g) || []).pop()?.match(/-?[\d.]+/)[0]);
  return { I, TP };
}
function prepAudio(src, name, { start = 0, length = null, fade = 0, loudness = null } = {}) {
  const file = resolve(project, src);
  mkdirSync(audioDir, { recursive: true });
  const out = join(audioDir, name);
  const af = [`atrim=start=${start}${length != null ? `:end=${r3(start + length)}` : ""}`, "asetpts=PTS-STARTPTS"];
  if (length != null && fade > 0) af.push(`afade=t=out:st=${r3(Math.max(0, length - fade))}:d=${fade}`);
  const r = spawnSync("ffmpeg", ["-v", "error", "-y", "-i", file, "-af", af.join(","), "-ar", "48000", "-ac", "2", "-c:a", "pcm_f32le", out], { encoding: "utf8" });
  if (r.status !== 0) { fail(`ffmpeg could not prepare ${src}: ${r.stderr}`); return null; }
  let gain = 0;
  if (loudness) {
    const limit = (10 ** (loudness.ceiling / 20)).toFixed(4);
    const tmp = out.replace(/\.wav$/, ".tmp.wav");
    const level = g => spawnSync("ffmpeg", ["-v", "error", "-y", "-i", out, "-af",
      `highpass=f=25,volume=${g}dB,alimiter=limit=${limit}:attack=5:release=60:level=disabled`, "-c:a", "pcm_s24le", tmp], { encoding: "utf8" });
    const m = loudnessOf(out);
    // Clips too short for a loudness reading (under 0.4 s) and sound effects (no target) still
    // get the ceiling; make-up gain is capped at +12 dB so a quiet tail is never pumped up.
    if (loudness.I != null && Number.isFinite(m.I) && m.I > -70) {
      gain = r2(loudness.I - m.I);
      if (gain > 12) { warn(`${src} is very quiet from its start point (${m.I.toFixed(1)} LUFS); check the start time. Boost capped at +12 dB.`); gain = 12; }
    }
    let g = level(gain);
    // The limiter costs a little loudness on dense masters; one correction pass wins it back,
    // capped at 2 dB so the limiter never squashes the track.
    if (g.status === 0 && loudness.I != null && Number.isFinite(m.I) && m.I > -70 && gain < 12) {
      const after = loudnessOf(tmp).I;
      const extra = Number.isFinite(after) ? Math.max(0, Math.min(2, loudness.I - after, 12 - gain)) : 0;
      if (extra > 0.2) { gain = r2(gain + extra); g = level(gain); }
    }
    if (g.status !== 0) { fail(`ffmpeg could not level ${src}: ${g.stderr}`); return null; }
    renameSync(tmp, out);
  }
  return { src: relative(project, out), length: probeAudio(out), gain };
}
